package com.november.mcphone.feature.chat;

import net.minecraft.network.chat.Component;

/**
 * 一次操作的结果，外加"这事要不要跟玩家说、说什么"。
 *
 * ================================================================
 * 为什么把话放进结果里
 * ================================================================
 *
 * 好友那边有 FriendOutcome 和一个 switch 把六种结果翻成四句话，传送那边
 * 有 TeleportOutcome 和另一个几乎一样的方法。加第三个功能就是第三个枚举
 * 加第三份 switch，而那些 switch 全在网络层——一个只该管"怎么送达"的地方，
 * 却攒了一堆"该说什么"。
 *
 * 现在结果自己说得出那句话，网络层只剩一个 tell：拿到话就走动作栏发出去，
 * 拿到 null 就闭嘴。加新功能时不必再碰网络层。
 *
 * ================================================================
 * 为什么是 Component 而不是翻译键
 * ================================================================
 *
 * 有的话带参数（"你的好友已满（上限 %s 人）"里那个上限就是 FriendData 的
 * 常量）。只返回一个键的话，参数得由网络层准备——那等于让它重新知道每种
 * 结果需要什么参数，绕回原点。
 *
 * 分工是清楚的：说什么由结果决定，怎么送达（动作栏、聊天框、还是不说）
 * 由网络层决定。
 */
public interface ChatOutcome {

    /**
     * 要告诉玩家的那句话；返回 null 表示这一种不必说。
     *
     * 什么时候该返回 null：成功（界面上看得见）、以及正常客户端根本走不到
     * 的路径（身上没手机、对方不是好友）。后者尤其不能说——那等于告诉
     * 伪造客户端是哪条规则拦住了它。
     */
    Component message();
}
