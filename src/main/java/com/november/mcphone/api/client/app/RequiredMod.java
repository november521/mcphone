package com.november.mcphone.api.client.app;

/**
 * 一个 App 依赖的外部模组 —— 「联动 App」那一页显示的就是它。
 *
 * ================================================================
 * 为什么不只写一个 modid
 * ================================================================
 *
 * 因为要显示给玩家看的那一刻，那个模组【多半正好没装】。
 *
 * 装了的话，模组名可以从 ModList 里问出来；而没装时 ModList 里什么都没有，
 * 只剩一个 modid。让玩家看到「需要 mcef」不算说明白——他不知道那是哪个模组、
 * 该去哪儿找，而这一页存在的全部理由就是回答这个问题。
 *
 * 所以显示名必须由声明方自己写死，不能指望运行时查。
 *
 * ================================================================
 * 这里刻意没有下载链接
 * ================================================================
 *
 * 想过加一个 url 字段，让玩家点了直接用手机里的浏览器打开。但那会造出一个
 * 死结：浏览器 App 本身就是个联动 App，没装 MCEF 时它不可用——而"没装 MCEF"
 * 恰恰是最需要那个链接的时候。
 *
 * 一个只在你已经不需要它时才能用的按钮，不如不做。
 *
 * @param modId       模组 id，与 {@code ModList.isLoaded} 用的是同一个值
 * @param displayName 给玩家看的名字，例如 "Waystones（传送石碑）"。
 *                    自己写死，别在运行时查——要显示它的时候多半查不到
 */
public record RequiredMod(String modId, String displayName) {}
